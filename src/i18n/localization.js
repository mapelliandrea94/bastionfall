export function gameText(value, language = getLanguage()) {
  if (value == null) return value;
  if (normalizeLanguage(language) !== SUPPORTED_LANGUAGES.IT_IT) return value;
  return GAME_TEXT_IT[String(value)] ?? value;
}

export function normalizeLanguage(value) {
  return value === SUPPORTED_LANGUAGES.IT_IT ? SUPPORTED_LANGUAGES.IT_IT : SUPPORTED_LANGUAGES.EN_US;
}

export function getLanguage() {
  if (typeof window === 'undefined') return SUPPORTED_LANGUAGES.EN_US;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored) return normalizeLanguage(stored);
  const browserLanguage = String(window.navigator?.language ?? '').toLowerCase();
  return browserLanguage.startsWith('it') ? SUPPORTED_LANGUAGES.IT_IT : SUPPORTED_LANGUAGES.EN_US;
}

export function setLanguage(language) {
  const normalized = normalizeLanguage(language);
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, normalized);
    document.documentElement.lang = normalized;
  }
  return normalized;
}

export function t(key, params = {}, language = getLanguage()) {
  const normalized = normalizeLanguage(language);
  const template = STRINGS[normalized]?.[key] ?? STRINGS['en-US']?.[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

